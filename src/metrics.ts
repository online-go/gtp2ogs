import * as fs from "fs";
import { Counter, Gauge, Histogram, Registry } from "prom-client";
import { config } from "./config";
import { trace } from "./trace";

class Metrics {
    private registry: Registry;
    private before_collect: (() => void)[] = [];

    readonly server_connected: Gauge;
    readonly server_disconnects: Counter;
    readonly active_games: Gauge<"speed">;
    readonly bot_startups: Counter;
    readonly bot_failures: Counter;
    readonly bot_failure_resigns: Counter;
    readonly move_rejections: Counter;
    readonly games_accepted: Counter;
    readonly games_refused: Counter<"reason">;
    readonly games_finished: Counter<"result" | "outcome">;
    readonly chat_messages_received: Counter;
    readonly bot_moves: Counter<"size">;
    readonly bot_move_duration: Histogram<"size">;
    readonly bot_pool_queue_length: Gauge<"pool">;
    readonly bot_acquire_duration: Histogram<"pool">;
    private last_updated: Gauge;

    constructor() {
        this.registry = new Registry();
        const registers = [this.registry];

        this.server_connected = new Gauge({
            name: "gtp2ogs_server_connected",
            help: "Whether the bot is currently connected to the OGS server (1 = connected, 0 = disconnected)",
            registers,
        });
        this.server_connected.set(0);

        this.server_disconnects = new Counter({
            name: "gtp2ogs_server_disconnects_total",
            help: "Total number of disconnections from the OGS server",
            registers,
        });
        this.active_games = new Gauge({
            name: "gtp2ogs_active_games",
            help: "Current number of active (non-paused) games by speed",
            labelNames: ["speed"],
            registers,
        });
        this.bot_startups = new Counter({
            name: "gtp2ogs_bot_startups_total",
            help: "Total number of bot process startups",
            registers,
        });
        this.bot_failures = new Counter({
            name: "gtp2ogs_bot_failures_total",
            help: "Total number of bot failures",
            registers,
        });
        this.bot_failure_resigns = new Counter({
            name: "gtp2ogs_bot_failure_resigns_total",
            help: "Total number of games resigned due to bot failure",
            registers,
        });
        this.move_rejections = new Counter({
            name: "gtp2ogs_move_rejections_total",
            help: "Total number of bot moves rejected by the OGS server",
            registers,
        });
        this.games_accepted = new Counter({
            name: "gtp2ogs_games_accepted_total",
            help: "Total number of accepted games",
            registers,
        });
        this.games_refused = new Counter({
            name: "gtp2ogs_games_refused_total",
            help: "Total number of refused games by reason",
            labelNames: ["reason"],
            registers,
        });
        this.games_finished = new Counter({
            name: "gtp2ogs_games_finished_total",
            help: "Total number of finished games by result and outcome",
            labelNames: ["result", "outcome"],
            registers,
        });
        this.chat_messages_received = new Counter({
            name: "gtp2ogs_chat_messages_received_total",
            help: "Total number of game chat messages received from other players",
            registers,
        });
        this.bot_moves = new Counter({
            name: "gtp2ogs_bot_moves_total",
            help: "Total number of moves generated by the bot",
            labelNames: ["size"],
            registers,
        });
        this.bot_move_duration = new Histogram({
            name: "gtp2ogs_bot_move_duration_seconds",
            help: "Duration of bot move generation in seconds",
            labelNames: ["size"],
            buckets: [0.1, 0.25, 0.5, 1, 2, 5, 10, 30, 60, 300],
            registers,
        });
        this.bot_pool_queue_length = new Gauge({
            name: "gtp2ogs_bot_pool_queue_length",
            help: "Current number of games waiting for an available bot in the pool",
            labelNames: ["pool"],
            registers,
        });
        this.bot_acquire_duration = new Histogram({
            name: "gtp2ogs_bot_acquire_duration_seconds",
            help: "Time spent waiting to acquire a bot from the pool in seconds",
            labelNames: ["pool"],
            buckets: [0.001, 0.01, 0.1, 0.5, 1, 5, 15, 60],
            registers,
        });
        this.last_updated = new Gauge({
            name: "gtp2ogs_last_updated_timestamp_seconds",
            help: "Unix timestamp in seconds when metrics were last written",
            registers,
        });

        setInterval(() => {
            void this.writePrometheus();
        }, 10000).unref();
    }

    onCollect = (fn: () => void): void => {
        this.before_collect.push(fn);
    };

    writePrometheus = async (): Promise<void> => {
        if (!config.metricsfile) {
            return;
        }
        try {
            if (config.username) {
                this.registry.setDefaultLabels({ bot: config.username });
            }
            for (const fn of this.before_collect) {
                fn();
            }
            this.last_updated.set(Date.now() / 1000);
            const buf = await this.registry.metrics();
            const tmp = `${config.metricsfile}.tmp`;
            await fs.promises.writeFile(tmp, buf, { encoding: "utf8", mode: 0o644 });
            await fs.promises.rename(tmp, config.metricsfile);
        } catch (e) {
            trace.error("Failed to write metrics file:", e);
        }
    };
}

export const metrics = new Metrics();
